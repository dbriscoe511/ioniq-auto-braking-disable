#!/usr/bin/env python3
"""Write src/secrets.h (gitignored) with the Wi-Fi credentials.

Values come from files (--ap-pass-file etc.) or environment variables
PS_AP_PASS, PS_STA_SSID, PS_STA_PASS. The home network (STA) is optional.
"""
import argparse, os, pathlib, sys

def c_str(s: str) -> str:
    out = []
    for b in s.encode():
        ch = chr(b)
        if 0x20 <= b < 0x7F and ch not in '\\"?':
            out.append(ch)
        else:
            out.append(f"\\{b:03o}")  # octal escape: always exactly 3 digits
    return '"' + "".join(out) + '"'

def get(file_arg, env):
    if file_arg:
        return pathlib.Path(file_arg).read_text().rstrip("\r\n")
    return os.environ.get(env, "")

ap = argparse.ArgumentParser()
ap.add_argument("--ap-pass-file")
ap.add_argument("--sta-ssid-file")
ap.add_argument("--sta-pass-file")
a = ap.parse_args()

ap_pass = get(a.ap_pass_file, "PS_AP_PASS")
ssid = get(a.sta_ssid_file, "PS_STA_SSID")
sta_pass = get(a.sta_pass_file, "PS_STA_PASS")
if len(ap_pass) < 8 or len(ap_pass) > 63:
    sys.exit("AP password must be 8-63 characters")
if len(ssid) > 32 or len(sta_pass) > 63:
    sys.exit("home SSID max 32 bytes, password max 63")

out = pathlib.Path(__file__).resolve().parent.parent / "src" / "secrets.h"
fd = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
with os.fdopen(fd, "w") as f:
    f.write("// Generated by tools/make_secrets.py. Do not commit.\n#pragma once\n")
    f.write(f"#define PS_AP_PASS {c_str(ap_pass)}\n")
    f.write(f"#define PS_STA_SSID {c_str(ssid)}\n")
    f.write(f"#define PS_STA_PASS {c_str(sta_pass)}\n")
print(f"wrote {out} (home network: {'yes' if ssid else 'no'})")
